"""Shared controls keep account-session work while routes and background reads change."""
import re
from playwright.sync_api import expect
from test_preview import server, browser_page, login  # noqa: F401


def test_routes_keep_filters_selection_draft_and_refresh_resets(server, browser_page):
    page, _ = browser_page
    login(page, server)
    page.get_by_label('项目', exact=True).fill('隔离')
    page.get_by_role('columnheader', name=re.compile('展示名')).get_by_role('button').click()
    page.get_by_role('link', name='MOD-02 i8 接入层', exact=True).click()
    page.get_by_label('动作', exact=True).select_option('print')
    page.get_by_role('link', name='MOD-03 付款通知书', exact=True).click()
    time = page.get_by_role('button', name=re.compile('^单据时间：'))
    expect(time).to_be_visible()
    page.get_by_role('button', name='项目筛选', exact=True).click()
    choices = page.get_by_role('group', name='导出项目候选')
    expect(choices.get_by_role('checkbox', name='隔离项目', exact=True)).to_be_visible()
    expect(choices.get_by_text('归档项目', exact=True)).to_be_visible()
    choices.get_by_role('checkbox', name='隔离项目', exact=True).check()
    page.get_by_role('heading', name='付款通知书', exact=True).click()
    expect(choices).not_to_be_visible()
    page.get_by_role('button', name='＋ 手动新增通知书', exact=True).click()
    field = page.get_by_label('草稿单据编码', exact=True)
    field.fill('LOCAL-DRAFT-A')
    page.route('**/api/m01/projects?status=all', lambda route: route.fulfill(status=500, json={'message':'定向重读失败'}))
    page.get_by_role('link', name='MOD-01 项目档案', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('项目更新失败')
    expect(page.get_by_role('cell', name='隔离项目', exact=True)).to_be_visible()
    page.unroute('**/api/m01/projects?status=all')
    page.get_by_role('button', name='重读项目', exact=True).click()
    expect(page.get_by_text('项目更新失败', exact=False)).to_have_count(0)
    expect(page.get_by_label('项目', exact=True)).to_have_value('隔离')
    expect(page.get_by_role('columnheader', name=re.compile('展示名'))).to_have_attribute('aria-sort', 'ascending')
    page.get_by_role('link', name='MOD-02 i8 接入层', exact=True).click()
    expect(page.get_by_label('动作', exact=True)).to_have_value('print')
    page.get_by_role('link', name='MOD-03 付款通知书', exact=True).click()
    expect(field).to_have_value('LOCAL-DRAFT-A')
    expect(page.get_by_role('button', name='项目筛选', exact=True)).to_contain_text('隔离项目')
    page.reload()
    expect(page.get_by_label('草稿单据编码', exact=True)).to_have_count(0)
    expect(page.get_by_role('button', name='项目筛选', exact=True)).to_contain_text('全部项目')


def test_time_modes_and_modal_discard_keep_input(server, browser_page):
    page, _ = browser_page
    login(page, server)
    page.get_by_role('button', name='＋ 手工建档', exact=True).click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_role('button', name='关闭弹窗', exact=True).click()
    expect(dialog).not_to_be_visible()
    page.get_by_role('button', name='＋ 手工建档', exact=True).click()
    dialog.get_by_label('项目全名', exact=True).fill('尚未保存的项目')
    dialog.press('Escape')
    expect(dialog.get_by_role('heading', name='放弃未保存的修改？')).to_be_visible()
    dialog.get_by_role('button', name='继续编辑', exact=True).click()
    expect(dialog.get_by_label('项目全名', exact=True)).to_have_value('尚未保存的项目')
    dialog.get_by_role('button', name='取消', exact=True).click()
    dialog.get_by_role('button', name='放弃并关闭', exact=True).click()
    expect(dialog).not_to_be_visible()
    page.get_by_role('link', name='MOD-03 付款通知书', exact=True).click()
    time = page.get_by_role('button', name=re.compile('^单据时间：'))
    time.click()
    panel = page.get_by_role('group', name='选择单据时间', exact=True)
    expect(panel.get_by_role('button', name='季度', exact=True)).to_have_count(0)
    panel.get_by_role('button', name='跨月', exact=True).click()
    panel.get_by_role('button', name='3月', exact=True).click()
    panel.get_by_role('button', name='1月', exact=True).click()
    expect(panel).to_be_visible()
    panel.get_by_role('button', name='2月', exact=True).click()
    expect(time).to_contain_text(re.compile(r'\d{4}-01 ~ \d{4}-02'))
    time.click()
    panel.get_by_role('button', name='年', exact=True).click()
    expect(panel.locator('.time-picker-years button')).to_have_count(9)
    panel.press('Escape')
    expect(panel).not_to_be_visible()
    page.get_by_role('button', name='抓取 i8 付款通知书（按月）', exact=True).click()
    dialog = page.get_by_role('dialog')
    month = dialog.get_by_role('button', name=re.compile('^抓取月份：'))
    month.click()
    month_panel = page.get_by_role('group', name='选择抓取月份', exact=True)
    expect(month_panel.get_by_role('button', name='跨月', exact=True)).to_have_count(0)
    month_panel.get_by_role('button', name='上一年', exact=True).click()
    month_panel.get_by_role('button', name='2月', exact=True).click()
    expect(dialog).to_be_visible()
    dialog.get_by_role('button', name='关闭弹窗', exact=True).click()
    expect(dialog.get_by_role('heading', name='放弃未保存的修改？')).to_be_visible()
    dialog.get_by_role('button', name='放弃并关闭', exact=True).click()
    expect(dialog).not_to_be_visible()