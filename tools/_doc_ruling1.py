def find_line(prefix: str) -> int:
    hits = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    if len(hits) != 1:
        raise SystemExit(f"⛔ 锚 `{prefix[:40]}` 命中 {len(hits)} 次（期望 1）")
    return hits[0]


def repl_line(prefix: str, new_line: str, tag: str) -> None:
    i = find_line(prefix)
    lines[i] = new_line
    done.append(tag)
    print(f"  ✅ {tag}")


def insert_after(prefix: str, text_block: str, tag: str) -> None:
    i = find_line(prefix)
    lines.insert(i + 1, text_block)
    done.append(tag)
    print(f"  ✅ {tag}")


def sub1(old: str, new: str, tag: str) -> None:
    """整文件唯一子串替换（用于表内单元格，锚必须唯一）。"""
    global text
    joined = "\n".join(lines)
    n = joined.count(old)
    if n != 1:
        raise SystemExit(f"⛔ {tag}：子串命中 {n} 次（期望 1）\n{old[:120]}")
    joined = joined.replace(old, new)
    lines[:] = joined.split("\n")
    done.append(tag)
    print(f"  ✅ {tag}")


