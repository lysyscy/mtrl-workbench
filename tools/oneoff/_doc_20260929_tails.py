def _sink_blocks(lines: list[str]) -> tuple[list[str], list[tuple[str, str]]]:
    """按（起点行首, 终点行首）切出整块 ⇒ 返回（新行表, [(归档标题, 原文)…]）。"""
    out: list[str] = []
    moved: list[tuple[str, str]] = []
    i = 0
    while i < len(lines):
        hit = None
        for start, end, repl, title in SINK:
            if lines[i].startswith(start):
                hit = (start, end, repl, title)
                break
        if hit is None:
            out.append(lines[i])
            i += 1
            continue
        start, end, repl, title = hit
        j = i + 1
        while j < len(lines) and not lines[j].startswith(end):
            j += 1
        assert j < len(lines), f"找不到终点行首：{end}"
        body = "\n".join(lines[i:j])          # 含起点那一行（标题）一起搬
        moved.append((title, body))
        out.extend(repl.strip("\n").split("\n"))
        i = j
    return out, moved


