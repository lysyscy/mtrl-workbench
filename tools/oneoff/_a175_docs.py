def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    plan: list[tuple[pathlib.Path, str, str, str, str]] = []
    for path, label, old_t, new_t in EDITS:
        raw = path.read_text(encoding="utf-8", newline="")
        nl = "\r\n" if "\r\n" in raw else "\n"
        old, new = old_t.replace("{nl}", nl), new_t.replace("{nl}", nl)
        n = raw.count(old)
        assert n == 1, f"{label}：锚点命中 {n} 次（要**恰好 1 次**）—— 先核再改"
        assert new not in raw, f"{label}：新串已在 ⇒ 本脚本跑过了"
        plan.append((path, label, old, new, raw))
        print(f"  ✅ 锚点唯一：{label}（{path.name}）")

    # ── 台账 §三 删行 ＋ §四 加行（按行手术；⛔ 不靠长串匹配整行）──────────
    txt = PLAN.read_text(encoding="utf-8", newline="")
    nl = "\r\n" if "\r\n" in txt else "\n"
    lines = txt.replace("\r\n", "\n").split("\n")
    drop = [i for i, ln in enumerate(lines)
            if ln.startswith("| `TAIL-175` |") and "待你裁定" in ln]
    assert len(drop) == 1, f"§三 的 `TAIL-175` 行命中 {len(drop)} 行（要 1 行）"
    i_drop = drop[0]
    print(f"  ✅ 锚点唯一：§15 §三 删掉 `TAIL-175` 行（第 {i_drop + 1} 行）")
    hdr = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    assert len(hdr) == 1, f"§四 表头命中 {len(hdr)} 行（要 1 行）"
    i_hdr = hdr[0]
    assert i_drop < i_hdr, "§三 的行不在 §四 之前 —— 段序变了"
    assert lines[i_hdr + 1].startswith("| `TAIL-"), "§四 表头的下一行不是数据行 ⇒ 表结构变了"
    print(f"  ✅ 锚点唯一：§15 §四 表头之后插一行（表头在第 {i_hdr + 1} 行）")

    if not args.write:
        print(f"\n（`--check`：⛔ 未写；逐处 {len(plan)} 处 ＋ 台账删 1 行 / 加 1 行）")
        return 0

    # ⚠️⚠️ **台账那两处行手术必须排在前面**：`lines` 是**此刻**读到的文本算出来的；
    #   若先跑 EDITS（每处都会重写 PLAN）⇒ 拿旧 `lines` 写回会把那些改动**全部抹掉**（实测同款坑见过一次）。
    lines.pop(i_drop)
    # ⚠️ 删行后 `i_hdr` **已漂 1 行** ⇒ 重新定位（⛔ 别拿旧下标 +1/+2 硬算）
    hdr2 = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    assert len(hdr2) == 1, "删行后 §四 表头找不到/不唯一"
    lines.insert(hdr2[0] + 1, LEDGER_ROW)          # §四 那张表**没有** `|---|` 分隔行 ⇒ 紧跟表头插
    PLAN.write_text(nl.join(lines), encoding="utf-8", newline="")
    print("✅ 已写：§15 台账（§三 −1 行 · §四 ＋1 行）")

    for path, label, old, new, _stale in plan:
        raw = path.read_text(encoding="utf-8", newline="")   # ⚠️ 每处写前**重读盘**（旧 `raw` 会抹掉前一处）
        assert raw.count(old) == 1, f"{label}：重读后锚点命中 {raw.count(old)} 次"
        path.write_text(raw.replace(old, new, 1), encoding="utf-8", newline="")
        print(f"✅ 已写：{label}")

    print("\n接着：`doc_audit`（`T4` 核四态 3 处 / `T6` 核台账计数）⇒ `audit_meta` ⇒ 12 把尺子")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
