def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    apply = a.write and not a.check

    for i, (path, old, new) in enumerate(EDITS, 1):
        text = path.read_text(encoding="utf-8", newline="")
        n = text.count(old)
        tag = path.relative_to(ROOT).as_posix()
        if n != 1:
            print(f"  ⛔ #{i} `{tag}`：锚点命中 **{n}** 处（要 1）⇒ 停手，别猜：{old[:48]}…")
            return 2
        if "2026-09-29" in old:
            print(f"  ⏭ #{i} `{tag}`：看着已改过 ⇒ 跳过")
            continue
        print(f"  ✓ #{i} `{tag}`：+{len(new.splitlines()) - len(old.splitlines())} 行 / {len(old)}→{len(new)} 字")
        if apply:
            path.write_text(text.replace(old, new, 1), encoding="utf-8", newline="")

    print("\n" + ("🔧 --write 已落盘" if apply else "🧪 --check（干跑，未落盘）"))
    print("   下一步：`doc_audit`（`T10`/`T13` 应转绿）＋ `audit_meta` 必须修 0 ＋ 全套 `_run_rulers.py`")
