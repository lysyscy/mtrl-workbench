def main() -> int:
    apply = "--apply" in sys.argv
    raw = PLAN.read_bytes()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8").replace("\r\n", "\n")
    back = text.replace("\n", "\r\n") if crlf else text
    if back.encode("utf-8") != raw:
        print("⛔ 行尾 round-trip 不一致 ⇒ 不动")
        return 1

    errors: list[str] = []
    for desc, old, new in EDITS:
        n = text.count(old)
        if n != 1:
            errors.append(f"{desc} —— 命中 {n} 次（期望 1）")
            continue
        text = text.replace(old, new, 1)

    print("=" * 80)
    print(("  写入" if apply else "  DRY-RUN（只报不写）") + " ·  TAIL-97 台账销号 ＋ TAIL-101 登记 ＋ §13.6 续记")
    print("=" * 80)
    print(f"  {PLAN.name} · 行尾={'CRLF' if crlf else 'LF'} · 替换 {len(EDITS)} 处")
    if errors:
        print("\n⛔ 有锚点对不上 ⇒ **一个字节都没写**：")
        for e in errors:
            print("   " + e)
        return 1
    if not apply:
        print("\n  （加 --apply 才真写。）")
        return 0
    PLAN.write_bytes((text.replace("\n", "\r\n") if crlf else text).encode("utf-8"))
    print("\n  ✅ 已写盘。")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main())
