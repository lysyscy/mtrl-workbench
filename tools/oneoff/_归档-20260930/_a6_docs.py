def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    plan: list[tuple[pathlib.Path, str, str, str, str]] = []
    for path, label, old_t, new_t in EDITS:
        raw = path.read_text(encoding="utf-8", newline="")
        nl = "\r\n" if "\r\n" in raw else "\n"
        old, new = old_t.replace("{nl}", nl), new_t.replace("{nl}", nl)
        n = raw.count(old)
        assert n == 1, f"{label}：锚点命中 {n} 次（要**恰好 1 次**）—— 先核再改"
        assert new not in raw, f"{label}：新串已在 ⇒ 本脚本跑过了"
        plan.append((path, label, old, new, raw))
        print(f"  ✅ 锚点唯一：{label}（{path.name}）")

    # ── 台账 §三 加行 ＋ §四 加行（按行手术；⚠️ 必须排在字符串编辑**之前**）──
    txt = PLAN.read_text(encoding="utf-8", newline="")
    nl = "\r\n" if "\r\n" in txt else "\n"
    lines = txt.replace("\r\n", "\n").split("\n")
    h3 = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 现状 | 你只需说 | 阶段 / 时机 | 状态 |"]
    h4 = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    assert len(h3) == 1 and len(h4) == 1, f"§三/§四 表头命中数 {len(h3)}/{len(h4)}（各要 1）"
    assert lines[h3[0] + 1].startswith("|---"), "§三 表头的下一行不是分隔行 ⇒ 表结构变了"
    assert lines[h4[0] + 1].startswith("| `TAIL-"), "§四 表头的下一行不是数据行 ⇒ 表结构变了"
    assert not any(ln.startswith("| `TAIL-177` |") for ln in lines), "`TAIL-177` 已在台账里"
    assert not any(ln.startswith("| `TAIL-176` |") for ln in lines), "`TAIL-176` 已在台账里"
    print(f"  ✅ 锚点唯一：§15 §三 表头（第 {h3[0] + 1} 行）· §15 §四 表头（第 {h4[0] + 1} 行）")

    if not args.write:
        print(f"\n（`--check`：⛔ 未写；逐处 {len(plan)} 处 ＋ 台账加 2 行）")
        return 0

    # ⚠️ 行手术先做（后面每处字符串编辑都会重写 PLAN ⇒ 拿旧 `lines` 会抹掉它们）
    lines.insert(h3[0] + 2, LEDGER_OPEN)                     # §三 有 `|---|` ⇒ 插在分隔行之后
    h4b = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    lines.insert(h4b[0] + 1, LEDGER_DONE)                    # §四 无分隔行 ⇒ 紧跟表头
    PLAN.write_text(nl.join(lines), encoding="utf-8", newline="")
    print("✅ 已写：§15 台账（§三 ＋1 行 · §四 ＋1 行）")

    for path, label, old, new, _stale in plan:
        raw = path.read_text(encoding="utf-8", newline="")    # ⚠️ 每处写前**重读盘**
        assert raw.count(old) == 1, f"{label}：重读后锚点命中 {raw.count(old)} 次"
        path.write_text(raw.replace(old, new, 1), encoding="utf-8", newline="")
        print(f"✅ 已写：{label}")

    print("\n接着：`doc_audit`（`T4` 四态 3 处 / `T6` 台账计数）⇒ `audit_meta` ⇒ 12 把尺子 ⇒ `_shell_smoke`")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
