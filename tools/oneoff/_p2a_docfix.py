CRLF: dict[Path, bool] = {}


def _read(p: Path) -> str:
    t = p.read_text(encoding="utf-8", newline="")          # ⛔ 保留 CRLF（本仓计划是 CRLF）
    CRLF[p] = "\r\n" in t
    return t


def _write(p: Path, text: str) -> None:
    """写回时**按原文件的换行风格归一** —— 插进去的 `\\n` 在 CRLF 文件里要变成 `\\r\\n`（⛔ 不混行尾）。"""
    text = text.replace("\r\n", "\n")
    if CRLF[p]:
        text = text.replace("\n", "\r\n")
    p.write_text(text, encoding="utf-8", newline="")


