files: dict[str, str] = {}
bad: list[str] = []
for name, old, new in EDITS:
    if name not in files:
        files[name] = (W / name).read_text(encoding="utf-8", newline="")
    # ⚠️ 壳件是 **CRLF**（`git` 那些 "LF will be replaced by CRLF" 的警告就是这个）⇒
    #    多行 old 在两套行尾下**各试一次**（⛔ 别全局 `.replace('\r\n','\n')` 后写回 ——
    #    那会把整个文件的字节换掉，`shell_verify` / 逐字节判据当场全乱）。
    for o, w in ((old, new), (old.replace("\n", "\r\n"), new.replace("\n", "\r\n"))):
        if files[name].count(o) == 1:
            files[name] = files[name].replace(o, w, 1)
            break
    else:
        bad.append(f"{name}: 命中 {files[name].count(old)} 次（含 CRLF 变体也没中）⇒ {old[:48]!r}")

if bad:
    print("⛔ 以下没命中（整批不写）：")
    for b in bad:
        print("   ", b)
    sys.exit(1)

for name, text in files.items():
    (W / name).write_text(text, encoding="utf-8", newline="")
    print(f"✅ 已改 {name}（{len(text)} 字节）")
print(f"\n共 {len(EDITS)} 处替换 · 全部命中 1 次 ✔")
