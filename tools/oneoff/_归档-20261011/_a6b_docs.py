def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    plan: list[tuple[pathlib.Path, str, str, str]] = []
    for path, label, old_t, new_t in EDITS:
        raw = path.read_text(encoding="utf-8", newline="")
        nl = "\r\n" if "\r\n" in raw else "\n"
        old, new = old_t.replace("{nl}", nl), new_t.replace("{nl}", nl)
        if old == new:
            raise AssertionError(f"{label}：新旧串相同（空操作 ⇒ 本脚本写错了）")
        n = raw.count(old)
        assert n == 1, f"{label}：锚点命中 {n} 次（要**恰好 1 次**）—— 先核再改"
        assert new not in raw, f"{label}：新串已在 ⇒ 本脚本跑过了"
        plan.append((path, label, old, new))
        print(f"  ✅ 锚点唯一：{label}（{path.name}）")

    # ── §15 行手术（⛔ 排在所有字符串编辑**之前**）────────────────────────
    txt = PLAN.read_text(encoding="utf-8", newline="")
    nl = "\r\n" if "\r\n" in txt else "\n"
    lines = txt.replace("\r\n", "\n").split("\n")
    hA = [i for i, ln in enumerate(lines)
          if ln.strip() == "| # | 事项 | 来源 | 不做会怎样 | 落点 | 阶段 / 时机 | 状态 |"]
    hC = [i for i, ln in enumerate(lines)
          if ln.strip() == "| # | 事项 | 现状 | 你只需说 | 阶段 / 时机 | 状态 |"]
    hD = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    assert len(hA) == 1 and len(hC) == 1 and len(hD) == 1, f"§一/§三/§四 表头命中 {len(hA)}/{len(hC)}/{len(hD)}"
    assert lines[hA[0] + 1].startswith("|---"), "§一 表头下一行不是分隔行"
    drop = [i for i, ln in enumerate(lines) if ln.startswith("| `TAIL-177` |") and "待你裁定" in ln]
    assert len(drop) == 1, f"§三 的 `TAIL-177` 行命中 {len(drop)} 行"
    for tid in ("TAIL-178", "TAIL-179"):
        assert not any(ln.startswith(f"| `{tid}` |") for ln in lines), f"`{tid}` 已在台账里"
    print(f"  ✅ 锚点唯一：§一 表头（第 {hA[0] + 1} 行）· §三 的 TAIL-177 行 · §四 表头（第 {hD[0] + 1} 行）")

    if not args.write:
        print(f"\n（`--check`：⛔ 未写；逐处 {len(plan)} 处 ＋ 台账：§一 ＋1 / §三 −1 / §四 ＋2）")
        return 0

    lines.insert(hA[0] + 2, ROW_178)                 # §一 有 `|---|` ⇒ 插在分隔行之后
    lines.pop(drop[0])                               # §三 删 TAIL-177
    hD2 = [i for i, ln in enumerate(lines) if ln.strip() == "| # | 事项 | 销号依据 | 日期 |"]
    assert len(hD2) == 1, "删行后 §四 表头不唯一"
    lines.insert(hD2[0] + 1, ROW_179)                # §四 无分隔行 ⇒ 紧跟表头（后插的在下面）
    lines.insert(hD2[0] + 1, ROW_177_DONE)
    PLAN.write_text(nl.join(lines), encoding="utf-8", newline="")
    print("✅ 已写：§15 台账（§一 ＋1 `TAIL-178` · §三 −1 `TAIL-177` · §四 ＋2）")

    for path, label, old, new in plan:
        raw = path.read_text(encoding="utf-8", newline="")     # ⚠️ 每处写前**重读盘**
        assert raw.count(old) == 1, f"{label}：重读后锚点命中 {raw.count(old)} 次"
        path.write_text(raw.replace(old, new, 1), encoding="utf-8", newline="")
        print(f"✅ 已写：{label}")

    print("\n接着：`doc_audit` ＋ `audit_meta`（`T4` 四态 3 处 / `T6` 台账计数与排期）⇒ 12 把尺子")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
