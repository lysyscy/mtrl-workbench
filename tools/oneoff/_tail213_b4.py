import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
INDEX = ROOT / "backend" / "app" / "web" / "index.html"

TIP_M04 = ('  <div class="tip">「<b>项目</b>」列填<b>展示名或仓库名</b>（⛔ 不是全名）—— 匹配不上标「未匹配」、重名标「重名 N 条」；'
           '系统<b>只提示、不拦截</b>（强制通过必须写备注）；手改列<b>会写入、不被导入覆盖</b>；'
           '数据按月归档，同月允许完全相同的行（靠「重复上报」提示，⛔ 不自动去重）。</div>\n')
TIP_M06 = ('  <div class="tip">材料数据是<b>单向流</b>：i8 → 库存单据（<b>唯一可改的源</b>）→ 本页（引用、派生只读）—— '
           '本页材料费<b>随库存单据变</b>、不独立维护；机械 6 列<b>先手录</b>；调整单<b>打在库存单据的行上</b>（不被 i8 导出覆盖）。</div>\n')
TIP_M11 = ('  <div class="tip">补正是<b>半年度对账</b>驱动的<b>偶发动作</b>（⛔ 不是月度例行）；差异<b>不独立成模块</b>、'
           '<b>归属「库存单据」</b>（修正只改库存单据）；本页是<b>手工清单、不自动同步</b>，可增可删、金额可正可负；'
           '月度会大表手填列<b>不补正</b>（下月填对即可）。</div>\n')
TIP_M12 = ('  <div class="tip">集采只做<b>台账管理</b>（竞价平台不接）；<b>集采欠款在这里算</b> —— 合同级实时、<b>不拆月度</b>'
           '（付款域不算它）；付款方式是<b>自由文本</b>、不限值（与付款域的枚举刻意不同）；'
           '<b>结算金额按有无贸易公司取不同子表口径</b>；主表那三列金额<b>只读</b>，录入走子表。</div>\n')
TIP_M15 = ('  <div class="tip">系统内只有 <b>2 人</b>、<b>业务权限无区别</b>（「角色」唯一的区别是<b>能不能管理账号</b>）；'
           '<b>停用 ≠ 删除</b>（删除是软删除：账号名保留、数据不销毁、可恢复）；'
           '<b>不能停用 / 删除「最后一个在用管理员」</b>、也不能删除自己；<b>系统外一律不设账号</b>。</div>\n')

JOBS = (
    ("m04", "<b>付款计划 = i8 付款通知书的「本月预算版」</b>", TIP_M04, ("审查结果", "数据按月归档")),
    ("m06", "<b>过程资料 = 每个项目每月一份的「项目成本台账」</b>", TIP_M06, ("材料数据单向流", "三个数据来源")),
    ("m11", "<b>补正是「半年度对账」驱动的偶发动作</b>", TIP_M11, ("补正分工", "登记方式")),
    ("m12", "<b>集采域（§6）只做台账管理</b>", TIP_M12, ("发票子表", "合同收发登记")),
    ("m15", "<b>系统内 2 人</b>（§1.5.1）", TIP_M15, ("防锁死", "系统外一律不设账号")),
)

TIP_LIMIT = 160     # 真机 ㉖ 红线是 200（默认展开）⇒ 本批每段必须远低于它


def main() -> int:
    text = INDEX.read_text(encoding="utf-8")
    for page, marker, tip, must in JOBS:
        assert text.count(marker) == 1, f"{page} 锚点命中 {text.count(marker)} 次"
        i = text.index(marker)
        a = text.rindex("${CALIB({", 0, i)
        b = text.index("]})}", i) + len("]})}")
        blk = text[a:b]
        assert 90 < len(blk) < 2600, f"{page} 那块长度 {len(blk)} 不像"
        for m in must:
            assert m in blk, f"{page} 那块里没有 {m!r} —— 不是我要删的那一块"
        n = len(re.sub(r"\s+", "", re.sub(r"<[^>]+>", "", tip)))
        assert n <= TIP_LIMIT, f"{page} 新写的页内说明 {n} 字 > {TIP_LIMIT}（真机 ㉖ 会红）"
        text = text[:a] + tip.rstrip("\n") + text[b:]

    assert text.count("${CALIB({") == 0, \
        f"全站 CALIB 调用点应清零 ⇒ 实为 {text.count('${CALIB({')}"
    INDEX.write_text(text, encoding="utf-8", newline="")
    print("✅ 批 4：m04 / m06 / m11 / m12 / m15 折叠块已撤（31 条 ⇒ 五段页内说明）"
          "⇒ 全站 CALIB 调用点清零（14 → 0）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
