"""`TAIL-117` 批次 3：**相似元素不许制造歧义**的离线判据（守则 §4.4 · §4.5）。

**守则落点**：§4.4（长得像但功能不同的入口，要在**文案或位置**上拉开）· §4.5（颜色只承担语义：
红=危险/错误、绿=成功/安全、黄=警告）· §2.4（要求与后果提前说）· §6 第 6、7 条。

⭐ **为什么只钉"相反动作"这一条**：颜色与相似元素是否"够拉开"最终要人眼判（守则 §4.5 的判据栏本就写明
   "壳 CSS token 审查"），但**有一类可以机器判死**：**一对语义相反的动作按钮，绝不能是同一款** ——
   `m03` 卡头上「批量剔除」与「恢复剔除」原本并排同款（都是 `class="btn"`），用户看错一眼就是
   "把要留的行剔掉"。⇒ 钉住：**危险的那个必须带 `dg`（红边）、恢复的那个不许带**。
真机那半在 `tools/probe/_shell_text.py` 的 **㉕**（同一个卡头里按钮文案不许重复）。

⚠️ 本件**不判**某个颜色"用得美不美"（那是 §10 与人的事），只判**语义色有没有用反**。
"""

from __future__ import annotations

from tests.acc_plugin import acc
from tests.shell_src import SHELL


def _btn(act: str) -> str:
    """取 `data-act="<act>"` 那个按钮的整段**开标签**（从 `<button` 到该标签的 `>`）。"""
    i = SHELL.find(f'data-act="{act}"')
    assert i > 0, f"找不到按钮 `data-act={act}`（判据的前提没了 —— 改了入口就同批改本件）"
    j = SHELL.find(">", i)
    return SHELL[SHELL.rfind("<button", 0, i):j + 1]


def _cls(tag: str) -> str:
    """开标签里的 `class="…"` 值（取不到就报出来，⛔ 别静默当成空串）。"""
    i = tag.find('class="')
    assert i > 0, f"这个按钮没有 `class`：{tag}"
    return tag[i + 7:tag.find('"', i + 7)]


@acc("ACC-UI-SHELL-001", "001-27")
def test_相反语义的一对按钮不许同款():
    """⭐ `批量剔除` 必须带 `dg`（危险 / 会影响统计的那一侧）、`恢复剔除` **不许**带（它是往回放）。

    ⚠️ **能证伪**：把两者改成同款（都 `btn`、或都 `btn dg`）⇒ 本件必红
       —— 这正是本批次改之前的形态（两个都 `class="btn"`、并排相邻）。
    """
    ex, un = _btn("batchEx"), _btn("batchUnEx")
    assert "dg" in _cls(ex).split(), \
        f"「批量剔除」是**危险动作**（默认不再显示、也不计入欠款）⇒ 必须用 `btn dg` 与恢复动作拉开；现在是 `{_cls(ex)}`"
    assert "dg" not in _cls(un).split(), \
        f"「恢复剔除」是**往回放**、不是危险动作 ⇒ 不许用危险色（守则 §4.5：颜色只承担语义）；现在是 `{_cls(un)}`"


@acc("ACC-UI-SHELL-001", "001-28")
def test_危险动作要让用户知道有退路():
    """⭐ 危险动作必须让用户知道**怎么退回来**（守则 §2.4 后果提前说 / §4.1 文案与行为一致）。

    ⚠️ 不钉死字符串 —— 只要求那枚按钮的**开标签（含悬停 `title`）里出现「恢复」二字**：
       退路的说法可以改，但"根本不提退路"就是缺陷（用户不敢点，或者点错了不知道怎么办）。
    """
    ex = _btn("batchEx")
    assert "恢复" in ex, \
        f"「批量剔除」的悬停里没提「怎么放回来」（用户不敢点 / 点错了不知道怎么退）：{ex}"
