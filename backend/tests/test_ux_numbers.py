@acc("ACC-UI-SHELL-001", "001-29")
def test_金额大数一律带单位():
    """⭐ KPI 那一格的金额**必须**走带单位的出口（`MONEY`），⛔ 不许裸 `M(`。

    ⚠️ **能证伪**：把任一处改回 `<div class="v">${M(d.合计)}</div>` ⇒ 本件必红
       （这正是本批次改之前的形态 —— 屏幕上就是一串没有单位的数字）。

    ⚠️⚠️ **2026-09-29（`A2` 逐页 · `TAIL-166`）复核出一条实质问题**：上面那条 `<div class="v">${M(`
    现在其实**只是一条墓碑** —— 它盯的那批 KPI（看板 4 ＋ 付款流水 4 ＋ 集采 3）**已被用户裁定全删**
    ⇒ 那个形态**本来就不复存在**，"不在"证明不了"现存的大数都带单位"。⇒ 本批补**正向守卫**：
    对**现存的**汇总大数逐处钉住（`m05` 台账标题行的「本项目当前欠款」＋ `m03` 勾选条的两个数）。
    ⛔ 仍不加"数量下限"（用户 2026-09-28 已裁定那不是他的口径）；这里钉的是**已经存在的那几处**。
    """
    assert "const MONEY=" in SHELL, "带单位的金额出口（`MONEY`）不见了 —— KPI 又会只剩一串数字"
    bare = '<div class="v">${M('
    assert bare not in SHELL, \
        f"KPI 大数字又出现裸 `M(`（只有数字、没有「元」）：搜 `{bare}`"
    # ⭐ 2026-09-29（`A2` 逐页 · `TAIL-166`）：**勾选汇总条**也是一处"汇总大数" —— 用户就是按它判断
    #    "这一批要付多少"；它原先是裸 `M(` ⇒ 屏幕上 `123,456.00`（单位靠猜），与上面那条口径同病。
    #    ⚠️ 上面那条判据用的是 `<div class="v">`（卡片里 KPI 的形态），**扫不到勾选条的 `<span class="v">`**
    #    ⇒ 这就是它的盲区（判据比口径弱 = 另一种假绿；同 `A1` 卡头那条的教训）。
    # ① 正向守卫之一：`m05` 逐月欠款台账标题行那个「本项目当前欠款（含期初）」
    assert '<b class="fc">${MONEY(cur)}</b>' in SHELL, \
        "`m05` 台账标题行的「本项目当前欠款」没带单位（那是这一页最显眼的数）"
    # ② 正向守卫之二：`m03` 勾选汇总条的两个数（用户按它们判断「这一批要付多少」）
    for tag, k in (("已勾选审批金额", "pkA"), ("已勾选本次应付", "pkP")):
        assert f'<span class="v">${{MONEY({k})}}</span>' in SHELL, \
            f"勾选条的「{tag}」没带单位（汇总大数一律走 `MONEY`）"
        assert f'<span class="v">${{M({k})}}</span>' not in SHELL, \
            f"勾选条的「{tag}」又退回裸 `M(`（只有数字、没有「元」）"
    # ⚠️ 2026-09-28（用户裁定）：「**数量下限**」不是用户定的口径 ⇒ 删掉计数断言。
    #    ⭐ 保留上面两条**形态**断言（`MONEY` 出口在 ＋ 不许裸 `M(`）—— 那才是这条 claim 的实质：
    #    **凡是金额大数，一律带单位**；而"页面上该放几个金额 KPI"是用户的事，⛔ 不是判据的事。
    #    （起因：看板清账删掉整行欠款 KPI ⇒ 计数掉到 3 ⇒ 假红。）


@acc("ACC-UI-SHELL-001", "001-30")
def test_不可得的金额不许冒充_0():
    """⭐ `null` ⇒ 「—」、**绝不显示 `0.00`**（守则：不可得 ≠ 0）—— 这是本项目反复强调的一条。

    ⚠️ 具体到 `MONEY`：它必须**先判 `null` 再拼单位**，⛔ 不能写成 `M(v)+'元'`
       （那会把「—」变成「— 元」，把"没取到"说成"是 0"）。
    """
    i = SHELL.find("const MONEY=")
    seg = SHELL[i:i + 220]
    assert "==null?" in seg or "== null ?" in seg, \
        f"`MONEY` 没先判 `null`（会显示「— 元」= 把『没取到』说成 0）：{seg[:120]}"


