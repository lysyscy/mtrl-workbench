    i = SHELL.find("const MONEY=")
    seg = SHELL[i:i + 220]
    assert "==null?" in seg or "== null ?" in seg, \
        f"`MONEY` 没先判 `null`（会显示「— 元」= 把『没取到』说成 0）：{seg[:120]}"


